  /*
     大会別、競技番号別、クラス別, ランキングlist
  */
IF OBJECT_ID('[dbo].vランキング無差別','V') IS NOT NULL
    DROP VIEW [dbo].vランキング無差別
GO
CREATE VIEW vランキング無差別
AS
   with ranking as (
    SELECT
	r.大会番号,
	プログラム.表示用競技番号,
  r.組,
  r.水路,
	rank() over (partition by r.大会番号 , プログラム.表示用競技番号 
	      ORDER BY r.ゴール ASC) AS 順位,
	プログラム.性別コード as 性別コード, 
	r.新記録判定クラス,
	プログラム.距離コード,
	プログラム.種目コード,
	r.ゴール,
		    [25m], [50m], [75m], [100m], [125m], [150m], [175m], [200m],
	   [225m], [250m], [275m], [300m], [325m], [350m], [375m], [400m], 
	   [425m], [450m], [475m], [500m], [525m], [550m], [575m], [600m],
	   [625m], [650m], [675m], [700m], [725m], [750m], [775m], [800m],
	   [825m], [850m], [875m], [900m], [925m], [950m], [975m], [1000m],
	   [1025m],[1050m],[1075m],[1100m],[1125m],[1150m],[1175m],[1200m],
	   [1225m],[1250m],[1275m],[1300m],[1325m],[1350m],[1375m],[1400m],
	   [1425m],[1450m],[1475m],[1500m],
選手.氏名 as 氏名,
  '' as 第1泳者,
	'' as 第2泳者,
	'' as 第3泳者,
	'' as 第4泳者,
  学種.学種,
  選手.学年,
  選手.生年月日,
	新記録印刷マーク,
	中間新記録マーク,
	選手.所属名称1 as 所属,
	プログラム.予決コード,
	プログラム.日付,
	大会設定.大会名１ as 競技会名,
	大会設定.開催地
    from 記録 r
	inner join 選手 on 選手.選手番号 = r.選手番号
	    and 選手.大会番号 = r.大会番号
	inner join プログラム on プログラム.競技番号 = r.競技番号
	    and プログラム.大会番号 = r.大会番号
	inner join 大会設定 on 大会設定.大会番号 = r.大会番号
	   inner join ラップ on ラップ.大会番号=r.大会番号　
	     and ラップ.競技番号=r.競技番号
	     and ラップ.組=r.組
	     and ラップ.水路=r.水路
  inner join 学種 on 学種.学種コード= 選手.学校コード

    where r.事由表示 = 0 
      and プログラム.種目コード < 6
      and r.オープン=0
      and r.ゴール <> ''

UNION ALL

    SELECT
	r.大会番号,
	プログラム.表示用競技番号,
  r.組,
  r.水路,
	rank() over (partition by r.大会番号, プログラム.表示用競技番号 
	    ORDER BY r.ゴール ASC) AS 順位,
	プログラム.性別コード as 性別コード,
		r.新記録判定クラス,
	プログラム.距離コード,
	プログラム.種目コード,
	r.ゴール,
		    [25m], [50m], [75m], [100m], [125m], [150m], [175m], [200m],
	   [225m], [250m], [275m], [300m], [325m], [350m], [375m], [400m], 
	   [425m], [450m], [475m], [500m], [525m], [550m], [575m], [600m],
	   [625m], [650m], [675m], [700m], [725m], [750m], [775m], [800m],
	   [825m], [850m], [875m], [900m], [925m], [950m], [975m], [1000m],
	   [1025m],[1050m],[1075m],[1100m],[1125m],[1150m],[1175m],[1200m],
	   [1225m],[1250m],[1275m],[1300m],[1325m],[1350m],[1375m],[1400m],
	   [1425m],[1450m],[1475m],[1500m],
    '' as 氏名, 
選手1.氏名 as 第1泳者, 
	選手2.氏名 as 第2泳者, 
	選手3.氏名 as 第3泳者, 
	選手4.氏名 as 第4泳者,
  '' as 学種,
  '' as 学年,
  '' as 生年月日,
	新記録印刷マーク,
	中間新記録マーク,
	リレーチーム.チーム名 as 所属,
	プログラム.予決コード,
	プログラム.日付,
	大会設定.大会名１ as 競技会名,
	大会設定.開催地
    from 記録 r
	left join クラス on クラス.クラス番号=r.新記録判定クラス
	    and クラス.大会番号=r.大会番号
	inner join リレーチーム on リレーチーム.チーム番号 = r.選手番号
	    and リレーチーム.大会番号 = r.大会番号
	inner join 選手 as 選手1 on 選手1.選手番号 = r.第１泳者
	    and 選手1.大会番号 = r.大会番号
	inner join 選手 as 選手2 on 選手2.選手番号 = r.第２泳者
	    and 選手2.大会番号 = r.大会番号
	inner join 選手 as 選手3 on 選手3.選手番号 = r.第３泳者
	    and 選手3.大会番号 = r.大会番号
	inner join 選手 as 選手4 on 選手4.選手番号 = r.第４泳者
	    and 選手4.大会番号 = r.大会番号
	inner join プログラム on プログラム.競技番号 = r.競技番号
	    and プログラム.大会番号 = r.大会番号
	inner join 大会設定 on 大会設定.大会番号 = r.大会番号
	inner join 予決 on 予決.予決コード=プログラム.予決コード
 	   inner join ラップ on ラップ.大会番号=r.大会番号　
	     and ラップ.競技番号=r.競技番号
	     and ラップ.組=r.組
	     and ラップ.水路=r.水路

   where r.事由表示 = 0
      and プログラム.種目コード > 5
      and r.オープン=0
      and r.ゴール <> ''
)
select ranking.* ,
        case 
              when ranking.性別コード=1 then '男子'
              when ranking.性別コード=2 then '女子'
              when ranking.性別コード=3 then '混成'
              when ranking.性別コード=4 then '混合'
              else ''
        end as 性別,
        case  
              when ranking.新記録判定クラス=0 then ''
              else クラス.クラス名称
        end as クラス名称,
        距離.距離,
        種目.種目
    from ranking
    inner join 距離 on 距離.距離コード=ranking.距離コード
    inner join 種目 on 種目.種目コード=ranking.種目コード
    inner join プログラム on プログラム.大会番号=ranking.大会番号
                      and プログラム.表示用競技番号=ranking.表示用競技番号
    left join クラス on クラス.クラス番号=ranking.新記録判定クラス
           and クラス.大会番号=ranking.大会番号
    inner join 予決 on 予決.予決コード=プログラム.予決コード

